# Заводим класс Solution, как того требует LeetCode.
class Solution:
# Создаём метод.
# self - ссылка на текущий объект класса. Без неё ничего работать не будет.
# nums: list[int] - входной массив, состоящий из целых чисел.
# k: int - максимально допустимое расстояние между индексами.
# -> bool - функция должна вернуть значение True, или False.
    def containsNearbyDuplicate(self, nums: list[int], k: int) -> bool:

# Создаём пустой словарь.
# В словаре мы будем хранить следующие значения:
# ключ - число из массива,
# значение - индекс, на котором это число встретилось последний раз.
# Словарь помогает быстро находить ранее встречающиеся числа и узнавать их
# последние индексы.
        seen = {}

# Запускаем цикл for.
# enumerate(nums) - встроенная функция Python, которая позволяет одновременно
# получать индекс элемента и само значение. Без enumerate() нам пришлось бы
# отдельно обращаться к индексам массива.
# Т.е. при каждой итерации: i получает индекс текущего элемента, а num
# получает значение текущего элемента.
        for i, num in enumerate(nums):

# Основная проверка всей задачи.
# Здесь мы используем два условия, объединённых оператором and.
# Оператор and означает, что оба условия должны быть истинными (True).
# Первое условие: num in seen.
# Проверяем, есть ли текущее число в нашем словаре.
# Например: seen = {1: 0, 2: 1, 3: 2}, num = 1. Проверяем: 1 in seen, Результат: True.
# Почему? Потому что число 1 уже есть среди ключей словаря.
# Если число раньше не встречалось, результат будет False.
# Второе условие: i - seen[num] <= k:
# Проверяем расстояние между индексами двух одинаковых чисел.
# i - индекс текущего элемента
# seen[num] - индекс, на котором это число встретилось ранее.
# i - seen[num] - расстояние между индексами.
# k - максимально допустимое расстояние.
# Например:
# i = 3
# seen[1] = 0
# k = 3
# Подставляем значения: 3 - 0 <= 3
# Получаем: 3 <= 3 // Результат: True
            if num in seen and i - seen[num] <= k:

# Если оба условия из предыдущей строки выполнились, значит:
# мы нашли одинаковое число и расстояние между индексами не превышает k.
# Следовательно, задача решена! Возвращаем True и прекращаем выполнение функции.
                return True

# Эта строка выполняется, если предыдущая проверка не вернула True.
# Мы записываем текущее число в словарь и сохраняем его индекс.
# Например: 
# num = 1
# i = 0
# После выполнения:
# seen[1] = 0
# В словаре появится запись:
# {1: 0}
# Если число уже было в словаре, его индекс обновится.
# Например:
# seen = {1: 0}
# Теперь мы встретили число 1 на индексе 3.
# Если проверка расстояния не прошла, выполняем:
# seen[1] = 3
# Теперь словарь: seen = {1: 3}
# Старый индекс 0 заменился новым индексом 3.
# Почему это важно? 
# Потому что мы храним именно последний индекс числа. Благодаря этому
# всегда можем проверить расстояние до самого близкого предыдущего повторения. 
            seen[num] = i

# Эта строка выполнится только в том случае, если цикл полностью завершился и
# подходящая пара одинаковых чисел не была найдена.
# Т.е. мы проверили весь массив, но не нашли двух одинаковых чисел на расстоянии
# не более k, поэтому возвращаем False.
        return False