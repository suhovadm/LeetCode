# Заводим класс Solution, как того требует LeetCode.
class Solution:
# Объявляем функцию reverseStr.
# self - ссылка на экземпляр класса. В нашем случае, она ни на что не ссылается.
# На вход подаём s: str - строку и k: int - целое число.
# На выход: -> str, т.е. функция должна вернуть строку.
    def reverseStr(self, s: str, k: int) -> str:
# Преобразуем строку в список символов.
# Например:
# s = "abcdefg"
# chars = list(s)
# Получаем ['a', 'b', 'c', 'd', 'e', 'f', 'g']
# Зачем это нужно? Потому что строки в Python неизменяемые, а элементы списка можно менять.
        chars = list(s)

# 0 - начинаем с нулевого индекса.
# len(chars) - длина списка (считаем символы).
# 2 * k - шаг цикла. Если k = 2, то шаг будет равен 4.
# Получается: i = 0, i = 4.
# Таким образом, мы начинаем обработку каждого нового блока из 2 * k символов.
        for i in range(0, len(chars), 2 * k):

# Переворачивание символов.
# Разберём на примере:
# chars = ['a', 'b', 'c', 'd', 'e', 'f', 'g']
# k = 2, i = 0.
# chars[i:i + k]
# Это то же самое что: chars[0:2]
# ['a', 'b']
# Теперь reversed(chars[i:i + k])
# Переворачиваем элементы:
# ['b', 'a']
# И записываем обратно в список:
# chars[i:i + k] = reversed(chars[i:i + k])
# Теперь список выглядит так:
# ['b', 'a', 'c', 'd', 'e', 'f', 'g']
# На следующей итерации i = 4.
# Переворачиваем:
# ['e', 'f']
# Получаем:
# ['b', 'a', 'c', 'd', 'f', 'e', 'g']
            chars[i:i + k] = reversed(chars[i:i + k])

# Возвращаем строку. Метод join() объединяет все элементы списка в одну.
# Было: ['b', 'a', 'c', 'd', 'f', 'e', 'g']
# Стало: "bacdfeg"
        return ''.join(chars)

# Символ g остаётся на месте, потому что он не образует полную пару из 2k символов,
# а оставишеся символы всё равно обрабатываются по правилу задачи.
# Т.е. главная идея:
chars[i:i + k] = reversed(chars[i:i + k])
# Мы берём срез списка, переворачиваем его и записываем обратно на то же место.
# Это и есть основная логика решения.