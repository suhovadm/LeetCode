# Заводим class, как того требует LeetCode.
class Solution:
# Объявляем функцию reverseBits.
# self - ссылка на текущий объект класса. В нашем случае необходима, т.к. без неё ничего не работает.
# n: int - на вход подаём целое число, которое нужно развернуть.
# -> int - функция должна вернуть целое число. Т.е. на выход подаём тоже целое число.
    def reverseBits(self, n: int) -> int:

# Создаём переменную result, в которой будем собирать перевёрнутые биты.
# Изначально она пуста, т.е. равна нулю.
        result = 0

# Запускаем цикл, который выполнится ровно 32 раза. Так указано в ТЗ.
# Каждая итерация будет забирать 1 бит из исходного числа и добавлять его в результат.
# Символ _ означает, что нам НЕ нужна переменная счётчика цикла. 
        for _ in range(32):

# Основная работа алгоритма.
# n & 1 - получаем последний бит числа. & - это логическое И (and).
# n & 1 - всегда возвращает последний бит числа.
# result << 1 - сдвигаем результат влево. << - сдвигает все биты числа влево на указанное количество позиций.
# | - побитовое ИЛИ (or). Объединяем биты двух чисел.
# Таким образом мы добавляем извлечённый бит в конец результата.
# Получаем следующую последовательность действий:
# 1. Берём последний бит n.
# 2. Сдвигаем result влево.
# 3. Добавляем извлечённый бит в конец result.
            result = (result << 1) | (n & 1)
# Сдвигаем исходное число вправо на один бит.
# Зачем это нужно?
# Чтобы убрать уже обработанный последний бит и перейти к следующему.
            n >>= 1

# После 32 итераций возвращаем результат - число с перевёрнутым порядком бит.
        return result